package entidade;

public class Soma {

	private double a;
	private double b;
	private double c;
	public Soma(double a, double b, double c) {
		a = a;
		b = b;
		c = c;
	}
	public double getA() {
		return a;
	}
	public void setA(double a) {
		this.a = a;
	}
	public double getB() {
		return b;
	}
	public void setB(double b) {
		this.b = b;
	}
	public double getC() {
		return c;
	}
}
